// Registration for events, built on the event calendar and forms: visitors
// book a slot (a day and, where the day has times, a time) of an event.
//
// Public: the booking panel under each date of an article (the calendar's
// "event.actions" slot) and /bookings/cancel/:token, the page the link in the
// confirmation e-mail opens. For administrators, with no nav entry:
// /bookings/manage (registrations), /bookings/manage/new?event=<id> and
// /bookings/manage/:id (the editor: details, blocks of days and times with a
// live preview of the slots, the questions, the bookings), reached from the
// calendar's "event.manage" and "event.editor" slots. BookingsAdmin - the
// table of an event's bookings, one booking's detail with its history, edit
// and cancel - is exported for pages that want it elsewhere.
//
// Contributes to the calendar's slots:
//   event.actions - the booking panel (context `{ event }`)
//   event.manage  - a link to the event's registration in each row
//   event.editor  - the "Registration" panel in the editor of a saved event
//
// Signing in on the way (a registration for signed-in visitors only) goes
// through utils/returnPath.ts, so the visitor comes back to the article.
