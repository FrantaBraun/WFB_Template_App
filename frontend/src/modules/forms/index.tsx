// Forms: questions of seven types with conditions, for other modules to build
// on. The module has no public page and no nav entry - what it offers is the
// components exported below, which the module that owns a form embeds:
//   FormBuilder      the administrators' editor of a form's questions
//   FormRenderer     the visitor's form (conditions show and hide questions)
//   SubmissionList / SubmissionView / FormStats
//                    the administrators' view of the answers and their summary;
//                    they take their data as props, so a module can show only
//                    the answers that still count
// plus collectAnswers() (what to send to the server) and the types. Its one
// page, /forms/manage/:formId, shows every answer of a form and the summary
// for administrators; modules that use a form link to it with the form's id.
